"""
Phase 0 — Core domain model for the knowledge system.

Hierarchy
---------
    Workspace
        └── Page           (Notion page or local document)
                └── Block  (atomic content unit: paragraph, heading, code, …)
                        └── Chunk  (embedding unit, derived from 1-N Blocks)

DocumentVersion records every point-in-time snapshot of a Page and enables:
    - Incremental indexing  (skip pages whose content has not changed)
    - Time travel           (retrieve the knowledge state at any version)
    - Knowledge evolution   (compare diff_summary across versions)

Design notes
------------
- All enums use str as their mixin so they serialise naturally to JSON/YAML.
- BlockType values for Notion-origin content match the Notion API verbatim.
  LOCAL_* values are used for content from local files (PDF, Markdown, text).
- Chunk.to_chroma_meta() / to_document() bridge this model to the existing
  LangChain + Chroma retrieval layer while remaining backward-compatible with
  the legacy schema.py metadata keys.
"""

from __future__ import annotations

import hashlib
import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum


# ---------------------------------------------------------------------------
# Enums
# ---------------------------------------------------------------------------

class BlockType(str, Enum):
    """All block types that can appear in a Page.

    Notion API type strings are used verbatim where applicable.
    LOCAL_* variants cover content that originates from local file parsers.
    """

    # ── Text blocks (Notion API) ──────────────────────────────────────────
    PARAGRAPH          = "paragraph"
    HEADING_1          = "heading_1"
    HEADING_2          = "heading_2"
    HEADING_3          = "heading_3"
    HEADING_4          = "heading_4"
    BULLETED_LIST_ITEM = "bulleted_list_item"
    NUMBERED_LIST_ITEM = "numbered_list_item"
    TO_DO              = "to_do"
    TOGGLE             = "toggle"
    CODE               = "code"
    QUOTE              = "quote"
    CALLOUT            = "callout"
    EQUATION           = "equation"

    # ── Structural blocks (Notion API) ────────────────────────────────────
    TABLE              = "table"
    TABLE_ROW          = "table_row"
    DIVIDER            = "divider"
    TABLE_OF_CONTENTS  = "table_of_contents"

    # ── Reference / navigation blocks (Notion API) ───────────────────────
    CHILD_PAGE         = "child_page"
    CHILD_DATABASE     = "child_database"

    # ── Media / embed blocks (Notion API) ────────────────────────────────
    IMAGE              = "image"
    VIDEO              = "video"
    AUDIO              = "audio"
    FILE               = "file"
    PDF                = "pdf"
    BOOKMARK           = "bookmark"
    EMBED              = "embed"

    # ── Local-file-origin types ───────────────────────────────────────────
    # Used when content comes from the local file parsers (not Notion API).
    LOCAL_HEADING      = "local_heading"    # Markdown heading
    LOCAL_PARAGRAPH    = "local_paragraph"  # plain-text paragraph
    LOCAL_CODE         = "local_code"       # fenced code block (Markdown)
    LOCAL_TABLE        = "local_table"      # Markdown GFM table
    LOCAL_PAGE_TEXT    = "local_page_text"  # raw page content from PDF

    UNSUPPORTED        = "unsupported"


class ChangeType(str, Enum):
    """The nature of the change captured in a DocumentVersion."""

    CREATED = "created"
    UPDATED = "updated"
    DELETED = "deleted"


